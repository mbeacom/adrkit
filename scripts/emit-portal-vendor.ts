/**
 * Copy the plugin's layout, view, and theme modules into the portal, byte for byte.
 *
 *   bun run emit:portal-vendor            # write the copies
 *   bun run emit:portal-vendor -- --check # write nothing; exit 1 on any drift
 *
 * # Why this exists
 *
 * ADR-0054 clause 11: the portal draws the same board the Copilot canvas draws,
 * with the same layout, pan and zoom, and theme. Those three modules are owned
 * by the agent plugin (`packages/adapters/agent-plugin/extensions/adrkit/`), and
 * the plugin cannot import a module outside its own directory, so the portal
 * holds generated copies. A hand-maintained copy drifts; this is ADR-0040's
 * MANIFEST mechanism instead: regenerate, and `clean-clone-builds` asserts the
 * tree is unchanged (`bun run emit:portal-vendor && git diff --exit-code
 * packages/portal/src/vendor`).
 *
 * # What is copied, and what never is
 *
 * The set is pinned by name in {@link VENDORED}, never globbed: a glob would
 * pick up the next module someone adds beside these, and the plugin directory
 * also holds `board-page.mjs`, `board.mjs`, `panel-http.mjs`, and
 * `board-review-write.mjs`, which the portal must never carry (the last one is
 * the only module allowed to name the review verbs). The portal writes its own
 * page module. `packages/portal/test/vendor.test.ts` asserts the copied set,
 * the byte identity, no import of any kind, and no review verb named as a
 * command.
 *
 * Each copy is {@link header} followed by the source's bytes, unchanged. The
 * header is two line comments with no blank line after them, so the source's
 * own `// @ts-check` stays in the file's leading comments, where TypeScript
 * reads the pragma.
 *
 * # The failure mode this script must not have
 *
 * A generator that writes nothing leaves `git diff` clean, so the gate reports
 * green while checking nothing (ADR-0016). A missing source module or a
 * missing vendor directory therefore throws rather than no-ops. `git diff`
 * cannot see a copy that was deleted and committed (the script recreates it as
 * an untracked file), which is why the vendor test asserts that the directory
 * holds exactly the pinned set, and `bun test` runs in the same job.
 *
 * # Observed failing (ADR-0016)
 *
 * Recorded 2026-10-10 in the feat/portal worktree, macOS, Bun 1.4.2:
 *
 * - One byte appended to `packages/portal/src/vendor/board-view.mjs`:
 *   `--check` exited 1 naming `board-view.mjs`, and `vendor.test.ts` failed
 *   its byte-identity test. With that edit committed (in a scratch repository
 *   holding this script, the three sources, and the copies, since this
 *   change was not yet committed), the CI command `sh -c 'bun run
 *   emit:portal-vendor && git diff --exit-code packages/portal/src/vendor'`
 *   rewrote the copy and exited 1 printing the diff; on the clean commit it
 *   exited 0.
 * - One byte appended to the plugin's `canvas-theme.mjs` (the source side):
 *   `--check` exited 1 naming `canvas-theme.mjs`.
 * - A copy deleted: `--check` exited 1 naming it as missing, and
 *   `vendor.test.ts` failed "the vendor directory holds exactly the pinned
 *   set".
 * - Each restored; a rerun printed `already matches` and exited 0.
 */

import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const repoRoot = resolve(import.meta.dir, '..');

/** Where the plugin keeps the modules, relative to the repository root. */
export const SOURCE_DIR = 'packages/adapters/agent-plugin/extensions/adrkit';

/** Where the portal keeps its copies, relative to the repository root. */
export const VENDOR_DIR = 'packages/portal/src/vendor';

/** The copied set, pinned by name (ADR-0054 clause 11). Never a glob. */
export const VENDORED = ['board-layout.mjs', 'board-view.mjs', 'canvas-theme.mjs'] as const;

/** The generated-file header for one copy; the source's bytes follow it unchanged. */
export function header(name: string): string {
  return (
    `// Generated copy of ${SOURCE_DIR}/${name} (ADR-0054 clause 11).\n` +
    '// generated by bun run emit:portal-vendor; do not edit.\n'
  );
}

/** The bytes a copy must hold, given its source's bytes. */
export function render(name: string, source: Buffer): Buffer {
  return Buffer.concat([Buffer.from(header(name), 'utf8'), source]);
}

export interface Drift {
  readonly name: string;
  readonly reason: 'missing' | 'differs';
}

function readSource(root: string, name: string): Buffer {
  const path = join(root, SOURCE_DIR, name);
  if (!existsSync(path)) {
    throw new Error(`source module ${SOURCE_DIR}/${name} does not exist; refusing to generate nothing.`);
  }
  return readFileSync(path);
}

/** Compare every pinned copy against its source. Throws when a source is missing. */
export function findDrift(root: string = repoRoot): Drift[] {
  const drift: Drift[] = [];
  for (const name of VENDORED) {
    const expected = render(name, readSource(root, name));
    const target = join(root, VENDOR_DIR, name);
    if (!existsSync(target)) drift.push({ name, reason: 'missing' });
    else if (!readFileSync(target).equals(expected)) drift.push({ name, reason: 'differs' });
  }
  return drift;
}

/** Write every pinned copy that differs. Returns the names written. */
export function emit(root: string = repoRoot): string[] {
  const dir = join(root, VENDOR_DIR);
  mkdirSync(dir, { recursive: true });
  if (!statSync(dir).isDirectory()) throw new Error(`${VENDOR_DIR} is not a directory.`);

  const written: string[] = [];
  for (const { name } of findDrift(root)) {
    writeFileSync(join(dir, name), render(name, readSource(root, name)));
    written.push(name);
  }
  return written;
}

function main(argv: readonly string[]): number {
  const unknown = argv.filter((arg) => arg !== '--check');
  if (unknown.length > 0) {
    console.error(`emit-portal-vendor: unknown argument ${unknown[0]}; the only option is --check`);
    return 2;
  }

  if (argv.includes('--check')) {
    const drift = findDrift();
    if (drift.length === 0) {
      console.log(`emit-portal-vendor: ok - ${VENDOR_DIR} already matches the plugin (${VENDORED.length} modules)`);
      return 0;
    }
    for (const { name, reason } of drift) {
      console.error(`emit-portal-vendor: ${VENDOR_DIR}/${name} ${reason === 'missing' ? 'is missing' : `differs from ${SOURCE_DIR}/${name}`}`);
    }
    console.error('emit-portal-vendor: run `bun run emit:portal-vendor` and commit the result');
    return 1;
  }

  const written = emit();
  if (written.length === 0) {
    console.log(`emit-portal-vendor: ok - ${VENDOR_DIR} already matches the plugin (${VENDORED.length} modules)`);
  } else {
    console.log(`emit-portal-vendor: wrote ${written.map((name) => `${VENDOR_DIR}/${name}`).join(', ')}`);
  }
  return 0;
}

if (import.meta.main) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (error) {
    console.error(`emit-portal-vendor: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
